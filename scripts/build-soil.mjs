/**
 * build-soil.mjs — turn the PixelLab SOIL Wang-tileset metadata into the corner-lookup table the
 * runtime tilled-soil overlay uses (src/systems/SoilOverlay.ts).
 *
 * Same technique as scripts/build-wang-luts.mjs (which is owned by the map/terrain pipeline and
 * writes src/world/luts — this script deliberately writes to src/config/luts instead so the two
 * pipelines never collide): each of the 16 Wang tiles covers one combination of its 4 corners
 * being lower (SOIL) or upper (grass). The dual-grid soil renderer samples 4 farm tiles per
 * rendered vertex and needs cornerMask -> frame index in the 4x4 sheet (row-major, from each
 * tile's bounding_box).
 *
 * Mask bits (1 = corner is SOIL): bit0=NW, bit1=NE, bit2=SW, bit3=SE.
 *
 * Reads:  public/assets/tilesets/soil-meta.json  (downloaded PixelLab metadata)
 * Writes: src/config/luts/soil-grass.json  ({ lut: number[16], fullLower, fullUpper })
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const metaUrl = new URL('../public/assets/tilesets/soil-meta.json', import.meta.url);
const outUrl = new URL('../src/config/luts/soil-grass.json', import.meta.url);

const meta = JSON.parse(readFileSync(metaUrl, 'utf8'));
const tiles = meta.tileset_data.tiles;
const lut = new Array(16).fill(-1);
let fullLower = -1;
let fullUpper = -1;
for (const t of tiles) {
  const bb = t.bounding_box;
  const frame = (bb.y / 16) * 4 + bb.x / 16; // row-major index in the 4x4 sheet
  const c = t.corners;
  const mask =
    (c.NW === 'lower' ? 1 : 0) |
    (c.NE === 'lower' ? 2 : 0) |
    (c.SW === 'lower' ? 4 : 0) |
    (c.SE === 'lower' ? 8 : 0);
  lut[mask] = frame;
  if (mask === 15) fullLower = frame;
  if (mask === 0) fullUpper = frame;
}
const missing = lut.filter((v) => v === -1).length;
if (missing > 0) throw new Error(`soil-meta.json: ${missing} corner combinations unmapped`);

mkdirSync(new URL('../src/config/luts/', import.meta.url), { recursive: true });
writeFileSync(
  outUrl,
  JSON.stringify(
    {
      _comment:
        'GENERATED by scripts/build-soil.mjs from public/assets/tilesets/soil-meta.json — do not hand-edit. lut[cornerMask] = frame index in the 4x4 wang-soil sheet (bit0=NW,bit1=NE,bit2=SW,bit3=SE; bit set = corner is SOIL).',
      lut,
      fullLower,
      fullUpper,
    },
    null,
    2
  ) + '\n'
);
console.log(`wrote src/config/luts/soil-grass.json (fullLower=${fullLower}, fullUpper=${fullUpper})`);
