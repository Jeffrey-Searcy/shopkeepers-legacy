/**
 * SoilOverlay — renders tilled soil as a CONNECTED blob (dual-grid Wang autotiling) plus a wet
 * tint per watered tile, reading GameState.tiles. Tiles are scene-scoped
 * (`${scene}:${tx},${ty}`), and this overlay only reads ITS OWN scene's entries — the fix for
 * farm soil ghost-rendering onto the town/forest at the same coordinates.
 *
 * Why: the old per-tile rounded soil patches left ugly gaps between adjacent tilled tiles. This
 * uses the same dual-grid corner technique as the terrain (see src/world/TerrainRenderer.ts): a
 * blank tilemap layer of size (w+1)x(h+1) offset by (-TILE/2, -TILE/2), where the tile at vertex
 * (vx,vy) covers the corners of map cells (vx-1,vy-1)..(vx,vy). Each vertex picks its frame from
 * a LUT keyed by which of its 4 corner cells are soil — so adjacent tilled tiles merge into one
 * seamless dark-earth patch with grass-transition edges.
 *
 * The LUT (src/config/luts/soil-grass.json) is generated by scripts/build-soil.mjs from the
 * PixelLab soil tileset metadata. Watered tiles additionally get a translucent dark square
 * (edge-to-edge, so adjacent watered tiles also read connected) — Stardew's "wet soil" is just
 * the tilled art darkened.
 *
 * Phaser import is unavoidable here (this system owns display objects); all soil STATE stays in
 * GameState/FarmGridSystem.
 */
import Phaser from 'phaser';
import { TILE } from '../config/GameConfig';
import { GameState } from '../state/GameState';
import soilLutJson from '../config/luts/soil-grass.json';

/** Manifest key of the 4x4 soil<->grass Wang sheet (loaded as a 16px spritesheet). */
export const WANG_SOIL_KEY = 'wang-soil';

/** Depth just above the Wang terrain stack (-15..-13) and below crops (-8). */
const DEPTH_SOIL = -9;
/** Wet tint sits on the soil but under crops. */
const DEPTH_WET = -8.9;

/** Wet soil keeps the warm art visible under a subtle cool sheen instead of becoming a mud block. */
const WET_COLOR = 0x244f52;
const WET_ALPHA = 0.22;

interface SoilLut {
  lut: number[];
  fullLower: number;
  fullUpper: number;
}

export class SoilOverlay {
  private layer: Phaser.Tilemaps.TilemapLayer;
  /** Wet-tint rectangles keyed by "tx,ty" (present only for watered tiles). */
  private wet = new Map<string, Phaser.GameObjects.Rectangle>();
  private lut: SoilLut;

  /** GameState.tiles key prefix for THIS scene (soil state is scene-scoped). */
  private get keyPrefix(): string {
    return `${this.scene.scene.key}:`;
  }

  /**
   * Build the (empty) soil layer for a map of w x h tiles. Fail-loud when the Wang sheet or its
   * LUT is missing — a silent fallback here would ship invisible farmland.
   */
  constructor(
    private scene: Phaser.Scene,
    private w: number,
    private h: number
  ) {
    this.lut = soilLutJson as SoilLut;
    if (this.lut.lut.some((v) => v < 0)) {
      throw new Error(
        'SoilOverlay: soil-grass LUT is unbuilt — run `node scripts/build-soil.mjs` after downloading the soil tileset'
      );
    }
    if (!scene.textures.exists(WANG_SOIL_KEY)) {
      throw new Error(`SoilOverlay: texture "${WANG_SOIL_KEY}" missing (manifest entry?)`);
    }
    const map = scene.make.tilemap({
      tileWidth: TILE,
      tileHeight: TILE,
      width: w + 1,
      height: h + 1,
    });
    const tiles = map.addTilesetImage(WANG_SOIL_KEY, WANG_SOIL_KEY, TILE, TILE, 0, 0);
    if (!tiles) throw new Error('SoilOverlay: failed to attach the wang-soil tileset');
    const layer = map.createBlankLayer('soil', tiles, -TILE / 2, -TILE / 2);
    if (!layer) throw new Error('SoilOverlay: failed to create the soil layer');
    layer.setDepth(DEPTH_SOIL);
    this.layer = layer;
  }

  /** Refresh the soil art around one tile (its 4 surrounding vertices) + its wet tint. */
  refreshTile(tx: number, ty: number): void {
    for (let vy = ty; vy <= ty + 1; vy++) {
      for (let vx = tx; vx <= tx + 1; vx++) {
        this.refreshVertex(vx, vy);
      }
    }
    this.refreshWet(tx, ty);
  }

  /** Rebuild the whole overlay from GameState (scene (re)entry / after sleep). */
  refreshAll(): void {
    const gs = GameState.instance;
    // Wet tints: clear and rebuild (cheap — only watered tiles carry one).
    for (const rect of this.wet.values()) rect.destroy();
    this.wet.clear();
    // Vertices: full clear (index -1 renders nothing), then refresh around every soil tile.
    this.layer.fill(-1, 0, 0, this.w + 1, this.h + 1);
    for (const k of Object.keys(gs.tiles)) {
      if (!k.startsWith(this.keyPrefix)) continue; // another scene's soil — not ours to draw
      const [tx, ty] = k.slice(this.keyPrefix.length).split(',').map(Number);
      this.refreshTile(tx, ty);
    }
  }

  /** Recompute one dual-grid vertex: which of its 4 corner cells are soil -> LUT frame. */
  private refreshVertex(vx: number, vy: number): void {
    if (vx < 0 || vy < 0 || vx > this.w || vy > this.h) return;
    const soil = (x: number, y: number): boolean =>
      !!GameState.instance.tiles[`${this.keyPrefix}${x},${y}`];
    const mask =
      (soil(vx - 1, vy - 1) ? 1 : 0) | // NW
      (soil(vx, vy - 1) ? 2 : 0) | // NE
      (soil(vx - 1, vy) ? 4 : 0) | // SW
      (soil(vx, vy) ? 8 : 0); // SE
    if (mask === 0) {
      this.layer.removeTileAt(vx, vy, true);
    } else {
      this.layer.putTileAt(this.lut.lut[mask], vx, vy);
    }
  }

  /** Add/remove the wet tint square for one tile from its GameState soil state. */
  private refreshWet(tx: number, ty: number): void {
    const k = `${tx},${ty}`;
    const watered = GameState.instance.tiles[`${this.keyPrefix}${k}`] === 'watered';
    const existing = this.wet.get(k);
    if (watered && !existing) {
      // NOTE: alpha is set at creation (fillAlpha) — setAlpha() would MULTIPLY against it
      // (the night-tint bug); we never touch alpha after creation.
      const rect = this.scene.add
        .rectangle(tx * TILE, ty * TILE, TILE, TILE, WET_COLOR, WET_ALPHA)
        .setOrigin(0, 0)
        .setDepth(DEPTH_WET);
      this.wet.set(k, rect);
    } else if (!watered && existing) {
      existing.destroy();
      this.wet.delete(k);
    }
  }
}
